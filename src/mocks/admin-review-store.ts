export function createAdminReviewStore() {
  let reviewItems = JSON.parse(JSON.stringify(initialArticleReviewItems)) as AdminArticleReviewItem[];

  return {
    getQueueSummary(): ReviewQueueSummary {
      return {
        totalCount: reviewItems.length,
        currentIndex: 0,
        items: reviewItems.map((item) => ({
          articleId: item.articleId,
          articleCode: item.articleCode,
          title: item.title,
          bodyDeletionHoursRemaining: item.bodyDeletionHoursRemaining,
          usageBasisStatus: item.usageBasis.status,
        })),
      };
    },

    getArticleReview(articleId: number): AdminArticleReviewItem | null {
      const found = reviewItems.find((item) => item.articleId === articleId);
      return found ? JSON.parse(JSON.stringify(found)) : null;
    },

    submitDecision(articleId: number, req: ReviewDecisionRequest): AdminArticleReviewItem {
      const targetIndex = reviewItems.findIndex((item) => item.articleId === articleId);
      if (targetIndex === -1) {
        throw new Error(`Article with ID ${articleId} not found in review queue`);
      }

      const target = reviewItems[targetIndex];
      const now = new Date().toISOString();

      if (req.decisionType === "APPROVE") {
        target.homeApproved = req.homeApproved ?? true;
        target.quizApproved = req.quizApproved ?? true;
        target.summary.reviewStatus = target.homeApproved ? "APPROVED" : target.summary.reviewStatus;
        target.quizzes = target.quizzes.map((q) => ({
          ...q,
          review_status: target.quizApproved ? "APPROVED" : q.review_status,
          reviewed_at: now,
          reviewed_by: "dev-admin@newslittle.local",
        }));
        target.rejectedReason = null;
      } else if (req.decisionType === "REJECT") {
        target.homeApproved = false;
        target.quizApproved = false;
        target.summary.reviewStatus = "REJECTED";
        target.quizzes = target.quizzes.map((q) => ({
          ...q,
          review_status: "REJECTED",
          reviewed_at: now,
          reviewed_by: "dev-admin@newslittle.local",
        }));
        target.rejectedReason = req.reason ?? "사유 미입력";
      } else if (req.decisionType === "REGENERATE") {
        target.homeApproved = false;
        target.quizApproved = false;
        target.summary.reviewStatus = "PENDING";
        target.quizzes = target.quizzes.map((q) => ({
          ...q,
          review_status: "PENDING",
          reviewed_at: null,
          reviewed_by: null,
        }));
        target.rejectedReason = `재생성 요청: ${req.reason ?? "품질 개선"}`;
      }

      return JSON.parse(JSON.stringify(target));
    },

    reset() {
      reviewItems = JSON.parse(JSON.stringify(initialArticleReviewItems));
    },
  };
}

export const mockAdminReviewStore = createAdminReviewStore();
